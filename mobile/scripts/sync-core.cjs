// Bundle the existing handlers without changing their business rules or using eval/WebView.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '../..');
const files = ['house-rights.js', 'business-guide.js', 'app.js'];
const sources = files.map(file => fs.readFileSync(path.join(root, file), 'utf8'));
const hash = crypto.createHash('sha256').update(sources.join('\n')).digest('hex');
const output = `// Generated by scripts/sync-core.cjs. Edit the original web sources instead.\n// Source SHA256: ${hash}\nmodule.exports = function bootCore(ports) {\nconst { document, window, localStorage, location, FormData, URL, Blob, setTimeout, clearTimeout } = ports;\nconst structuredClone = value => JSON.parse(JSON.stringify(value));\n${sources.join('\n')}\nreturn { getState: () => state, action: handleAction, submit: handleForm, render, closeDialog,\n  nav: NAV, person, userId, totalInvoice, isPublicPost, listingView, roomLoad,\n  notify: flash, reset: window.__troday.reset };\n};\n`;
const target = path.join(root, 'mobile/src/generated/core.cjs');
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, output);
console.log(`Synced 3 business sources (${hash.slice(0, 12)})`);
